/**
 * Turn the two agents' raw outcomes into RESULTS.md.
 * Usage: npx tsx study/hook-failures/render.ts <gemini.json> <codex.json>
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const cases = JSON.parse(readFileSync(join(here, 'cases.json'), 'utf8')) as Array<{ id: string; describe: string }>;
const [geminiPath, codexPath] = process.argv.slice(2);
if (!geminiPath || !codexPath) throw new Error('usage: render.ts <gemini.json> <codex.json>');
const gemini = JSON.parse(readFileSync(geminiPath, 'utf8')) as Record<string, string>;
const codex = JSON.parse(readFileSync(codexPath, 'utf8')) as Record<string, string>;

const cell = (outcome: string | undefined): string => {
  if (outcome === undefined) throw new Error('missing outcome');
  return outcome === 'RUNS' ? '**runs**' : outcome === 'ASKS' ? 'asks the user' : 'blocked';
};

const rows = cases.map((c) => `| ${c.describe} | ${cell(gemini[c.id])} | ${cell(codex[c.id])} |`);
const opens = (r: Record<string, string>) =>
  cases.filter((c) => c.id !== 'nothing' && c.id !== 'allow' && r[c.id] === 'RUNS').map((c) => c.id);

const md = `# What happens to a tool call when the safety hook misbehaves

The hook was asked about \`rm -rf build\` and answered in ten different ways. "Runs" means the
agent goes ahead with the command. Every outcome comes from the agent's own code (see the
README for how), at a pinned commit. Generated by \`study/hook-failures/render.ts\`; CI fails if
this file no longer matches.

| The hook... | Gemini CLI | Codex |
| --- | --- | --- |
${rows.join('\n')}

Outside "allow" and "no opinion", the command still runs in these cases:

- Gemini CLI: ${opens(gemini).join(', ') || 'none'}
- Codex: ${opens(codex).join(', ') || 'none'}
`;
writeFileSync(join(here, 'RESULTS.md'), md);
process.stdout.write(md);
